/**
 * Converte o código ou nome da categoria para o formato padrão do usuário:
 * "cod. categoria - nome categoria" (Ex: "04.02.007 - PARAFUSOS/PORCAS/ARRUELAS")
 */
export function formatarCategoria(codigoOuNome) {
  if (!codigoOuNome) return 'Geral';
  const str = String(codigoOuNome).trim();
  if (!str) return 'Geral';

  // Se já estiver formatado como "codigo - descricao"
  if (str.includes(' - ')) {
    return str;
  }

  // Se for um código no dicionário SAP
  if (MAPA_CATEGORIAS_SAP[str]) {
    return `${str} - ${MAPA_CATEGORIAS_SAP[str]}`;
  }

  // Caso seja descrição pura ou código não cadastrado
  return str;
}
